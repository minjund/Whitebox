'use strict';
const assert = require('node:assert/strict');
const { start, move, over, restore } = require('../renderer/summary-2048');
const state = values => ({ cells: [...values, ...Array(16 - values.length).fill(0)], score: 0, best: 0, open: true });
const initial = start(100, () => 0);
assert.equal(initial.cells.filter(Boolean).length, 2);
assert.equal(initial.best, 100);
const merged = move(state([2, 2, 2, 2]), 'left', () => 0);
assert.deepEqual(merged.cells.slice(0, 4), [4, 4, 2, 0], 'each tile merges once, then exactly one tile spawns');
assert.equal(merged.score, 8);
assert.equal(merged.best, 8);
assert.deepEqual(move(state([2, 0, 2, 0]), 'right', () => 0).cells.slice(0, 4), [2, 0, 0, 4]);
const vertical = state([2]); vertical.cells[4] = 2;
assert.equal(move(vertical, 'up', () => 0).cells[0], 4);
assert.equal(move(vertical, 'down', () => 0).cells[12], 4);
const unmoved = state([2]); let randomCalls = 0;
assert.equal(move(unmoved, 'left', () => { randomCalls++; return 0; }), unmoved);
assert.equal(randomCalls, 0, 'invalid moves do not add a tile');
assert(over(state([2,4,2,4,4,2,4,2,2,4,2,4,4,2,4,2])));
assert(!over(state([2,2,4,8,4,8,16,32,8,16,32,64,16,32,64,128])));
assert.equal(move(state([1024,1024]), 'left', () => 0).cells[0], 2048);
assert.deepEqual(restore(JSON.parse(JSON.stringify(merged))), merged);
assert.equal(restore({ ...merged, cells: Array(16).fill(3) }), null);
assert.equal(restore({ ...merged, score: -1 }), null);
console.log('PASS 2048: four directions, single merge, scoring/best, no-op/no spawn, game over, 2048 and validated persistence');
