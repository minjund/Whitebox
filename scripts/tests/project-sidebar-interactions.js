'use strict';

// Exercise the real renderer with the isolated interaction fixture preload.
module.exports = async function exerciseProjectSidebar(win) {
  return win.webContents.executeJavaScript(`(async () => {
    const app = window.WhiteboxApp;
    const list = document.querySelector('#projectSidebarList');
    const frame = () => new Promise(resolve => requestAnimationFrame(() => requestAnimationFrame(resolve)));
    const check = (ok, message) => { if (!ok) throw new Error('Sidebar: ' + message); };
    const prefs = () => JSON.parse(localStorage.getItem(app.DASHBOARD_STORAGE_KEY) || '{}');
    const keydown = (target, key, options = {}) => target.dispatchEvent(new KeyboardEvent('keydown', { key, bubbles: true, cancelable: true, ...options }));
    app.state.sidebarExpandedProjects.clear();
    app.state.sidebarProjectSearch = '';
    document.querySelector('#sidebarProjectSearch').value = '';
    app.renderWorkspaces();
    check(!list.querySelector('[data-source-workspace], [data-sidebar-source-toggle], [aria-level="3"]'), 'source headings must be absent');
    check(!list.querySelector('[aria-expanded="true"]'), 'projects start collapsed');
    const first = list.querySelector('[data-sidebar-project-toggle]')?.closest('.project-sidebar-project');
    check(first, 'fixture needs a project with tasks');
    const projectKey = first.dataset.sidebarProjectKey;
    const projectPath = first.querySelector('[data-workspace]').dataset.workspace;
    const group = () => [...list.querySelectorAll('[data-sidebar-project-key]')].find(node => node.dataset.sidebarProjectKey === projectKey);
    const row = () => group().querySelector('.project-sidebar-item');
    const toggle = () => group().querySelector('[data-sidebar-project-toggle]');
    const tasks = () => group().querySelector('.project-sidebar-sessions');
    app.state.workspaceSource = 'builtin.opencode';
    row().click(); await frame();
    row().click(); await frame();
    check(app.state.workspace === projectPath && app.state.workspaceSource === 'all', 'name always selects all task sources');
    check(row().getAttribute('aria-expanded') === 'false', 'name must not expand tasks');
    toggle().click(); await frame();
    check(row().getAttribute('aria-expanded') === 'true' && !tasks().hidden, 'disclosure expands tasks');
    check(prefs().sidebarExpandedProjects.includes(projectKey), 'expansion persists');
    check(document.activeElement === row(), 'disclosure restores tree focus');
    const ids = [...tasks().querySelectorAll('[data-sidebar-session-id]')].map(node => node.dataset.sidebarSessionId);
    check(ids.length > 0 && ids.length === new Set(ids).size, 'unique root tasks');
    check([...tasks().querySelectorAll('[role="treeitem"]')].every(node => node.getAttribute('aria-level') === '2'), 'tasks are immediate children');
    keydown(row(), 'ArrowRight'); await frame();
    check(document.activeElement.dataset.sidebarSessionId === ids[0], 'right arrow enters first task');
    keydown(document.activeElement, 'ArrowLeft'); await frame();
    check(document.activeElement === row(), 'left arrow returns to project');
    keydown(row(), 'ArrowLeft'); await frame();
    check(tasks().hidden && !prefs().sidebarExpandedProjects.includes(projectKey), 'left arrow collapses and saves');
    keydown(row(), 'ArrowRight'); await frame();
    row().click(); await frame();
    check(!tasks().hidden, 'reselecting project preserves expansion');

    const originalCount = list.querySelectorAll('[data-sidebar-project-key]').length;
    const search = document.querySelector('#sidebarProjectSearch');
    const query = value => { search.value = value; search.dispatchEvent(new Event('input', { bubbles: true })); };
    query(projectPath.toUpperCase());
    const matches = [...list.querySelectorAll('.project-sidebar-item')];
    check(matches.length > 0 && matches.every(node => node.dataset.workspace.toUpperCase().includes(projectPath.toUpperCase())), 'case-insensitive path search');
    query('no-project-matches-this-query');
    check(!list.querySelector('[data-sidebar-project-key]') && list.querySelector('.workspace-empty'), 'empty search state');
    check(app.state.workspace === projectPath, 'search never changes selected workspace');
    keydown(search, 'Escape');
    check(search.value === '' && list.querySelectorAll('[data-sidebar-project-key]').length === originalCount, 'escape clears search');
    document.querySelector('#sidebarCollapseAllBtn').click();
    check(!list.querySelector('[aria-expanded="true"]') && prefs().sidebarExpandedProjects.length === 0, 'collapse all');

    const sortable = () => [...list.querySelectorAll('[data-project-sortable]')];
    const orderBefore = sortable().map(node => node.dataset.projectSortable);
    check(orderBefore.length >= 2, 'fixture needs two reorderable projects');
    sortable()[1].querySelector('.project-sidebar-item').focus();
    keydown(document.activeElement, 'F10', { shiftKey: true }); await frame();
    const menu = document.querySelector('#projectSidebarMenu');
    check(menu.matches(':popover-open'), 'keyboard opens menu');
    const menuRect = menu.getBoundingClientRect();
    check(menuRect.left >= 0 && menuRect.right <= innerWidth && menuRect.bottom <= innerHeight, 'menu stays inside viewport');
    menu.querySelector('[data-sidebar-menu-action="up"]').click(); await frame();
    check(sortable()[0].dataset.projectSortable === orderBefore[1], 'menu moves project up');
    check(prefs().projectOrder.indexOf(orderBefore[1]) < prefs().projectOrder.indexOf(orderBefore[0]), 'menu reorder persists');
    keydown(sortable()[0].querySelector('.project-sidebar-item'), 'ArrowDown', { altKey: true }); await frame();
    check(sortable().map(node => node.dataset.projectSortable).join('|') === orderBefore.join('|'), 'keyboard restores original order');
    const source = sortable().at(-1), target = sortable()[0], sourceKey = source.dataset.projectSortable;
    const data = new Map();
    const transfer = { setData: (key, value) => data.set(key, value), getData: key => data.get(key) || '', setDragImage() {} };
    const drag = (node, type) => {
      const event = new Event(type, { bubbles: true, cancelable: true });
      Object.defineProperties(event, { dataTransfer: { value: transfer }, clientY: { value: target.getBoundingClientRect().top + 1 } });
      node.dispatchEvent(event);
    };
    drag(source.querySelector('.project-sidebar-drag-handle'), 'dragstart');
    drag(target, 'dragover'); drag(target, 'drop');
    check(sortable()[0].dataset.projectSortable === sourceKey, 'folder drag reorders projects');
    check(!list.querySelector('.project-sort-dragging, [data-project-drop-edge]'), 'drag state cleaned');
    app.state.projectOrder = orderBefore; app.renderWorkspaces(); app.saveDashboardPreferences();
    await new Promise(resolve => setTimeout(resolve, 270));
    toggle().click(); await frame();
    const stored = prefs();
    localStorage.setItem(app.DASHBOARD_STORAGE_KEY, JSON.stringify({ ...stored, workspaceSource: 'builtin.opencode', sidebarCollapsedSources: ['legacy'] }));
    app.loadQualityState(); app.renderWorkspaces();
    check(app.state.workspaceSource === 'all' && app.state.sidebarExpandedProjects.has(projectKey), 'legacy source selection migrates and expansion reloads');
    app.saveDashboardPreferences();
    const ptyTask = list.querySelector('[data-pty-focus-trigger="fixture-root"]');
    check(ptyTask, 'fixture root task is available');
    ptyTask.click();
    for (let attempt = 0; attempt < 100; attempt += 1) {
      if (app.state.ptyFocusSessionId === 'fixture-root' && !document.querySelector('#ptyFocusSurface').hidden) break;
      await new Promise(resolve => setTimeout(resolve, 50));
    }
    check(app.state.ptyFocusSessionId === 'fixture-root', 'task opens its exact PTY');
    check(app.state.workspace === projectPath && app.state.workspaceSource === 'all', 'task open preserves aggregate workspace');
    app.closePtyFocus({ restoreFocus: false });
    await frame();
    return { projects: originalCount, rootTasks: ids.length, selection: true, disclosure: true, search: true, keyboard: true, menu: true, drag: true, persistence: true, exactPty: true };
  })()`);
};
